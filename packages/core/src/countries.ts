export type CountryCode = (typeof countryCodes)[number]

export const countryCodeSchema = z.enum(countryCodes)

export type Country = { code: CountryCode; name: string }

const displayNames = new Map<Locale, Intl.DisplayNames>()

/** Name of a country in the given locale (e.g. "CM" → "Cameroun" in French). */
export function getCountryName(code: CountryCode, locale: Locale): string {
  let names = displayNames.get(locale)
  if (!names) {
    names = new Intl.DisplayNames([locale], { type: "region" })
    displayNames.set(locale, names)
  }
  return names.of(code) ?? code
}

/** Every country with its localized name, sorted alphabetically for the locale. */
export function getCountries(locale: Locale): Country[] {
  const collator = new Intl.Collator(locale)
  return countryCodes
    .map((code) => ({ code, name: getCountryName(code, locale) }))
    .sort((a, b) => collator.compare(a.name, b.name))
}
